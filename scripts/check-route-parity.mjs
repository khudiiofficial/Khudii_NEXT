function parseRegistry(text) {
  const found = new Set();
  const pattern = /(?:route|protectedRoute|openRoute)\(\s*['"](GET|POST|PUT|PATCH|DELETE)['"]\s*,\s*['"]([^'"]+)['"]/g;
  for (const match of text.matchAll(pattern)) found.add(`${match[1]} ${match[2]}`);
  return found;
}

const publicRoutes = parseRegistry(await readFile('src/server/public-routes.js', 'utf8'));
const adminRoutes = parseRegistry(await readFile('src/server/admin-routes.js', 'utf8'));

for (const route of expectedPublic) {
  if (!publicRoutes.has(route)) throw new Error(`Missing original public route: ${route}`);
}
for (const route of expectedAdmin) {
  if (!adminRoutes.has(route)) throw new Error(`Missing original admin route: ${route}`);
}

console.log(`Original backend route parity passed (${expectedPublic.length} public, ${expectedAdmin.length} admin).`);
